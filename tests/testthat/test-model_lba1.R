context("Single-Accumulator LBA")

test_that("rcogmod_lba1 produces valid reaction times and responds to parameters", {
  skip_on_cran()
  set.seed(123)
  n <- 10000  # Large sample size for reliable means

  # Parameter combinations for basic property tests
  param_combinations <- expand.grid(
    drift = c(1, 3),
    sigma = 1,
    sigmabias = 0.5,
    boundary = 0.5,
    ndt = 0.3
  )

  # 1. Basic property tests
  for (i in 1:nrow(param_combinations)) {
    params <- param_combinations[i, ]
    label <- sprintf("params(drift=%.1f, sigma=%.1f, sigmabias=%.1f, boundary=%.1f, ndt=%.1f)",
                     params$drift, params$sigma, params$sigmabias, params$boundary, params$ndt)
    rts <- rcogmod_lba1(n, drift = params$drift, sigma = params$sigma,
                   sigmabias = params$sigmabias, boundary = params$boundary, ndt = params$ndt)

    # Check for NA values
    if (any(is.na(rts))) {
      warning("NA values generated by rcogmod_lba1 for ", label)
      next
    }

    # All RTs should be >= ndt
    expect_true(all(rts >= params$ndt),
                label = paste(label, "- All RTs >= ndt"))

    # All RTs should be finite
    expect_true(all(is.finite(rts)),
                label = paste(label, "- All RTs are finite"))
  }

  # 2. Parameter sensitivity tests
  # Effect of drift: higher drift should decrease mean RT
  params_low_drift <- list(drift = 1, sigma = 1, sigmabias = 0.5, boundary = 0.5, ndt = 0.3)
  params_high_drift <- list(drift = 3, sigma = 1, sigmabias = 0.5, boundary = 0.5, ndt = 0.3)

  rts_low_drift <- rcogmod_lba1(n, drift = params_low_drift$drift, sigma = params_low_drift$sigma,
                           sigmabias = params_low_drift$sigmabias, boundary = params_low_drift$boundary,
                           ndt = params_low_drift$ndt)
  rts_high_drift <- rcogmod_lba1(n, drift = params_high_drift$drift, sigma = params_high_drift$sigma,
                            sigmabias = params_high_drift$sigmabias, boundary = params_high_drift$boundary,
                            ndt = params_high_drift$ndt)

  mean_low_drift <- mean(rts_low_drift)
  mean_high_drift <- mean(rts_high_drift)

  expect_true(mean_high_drift < mean_low_drift,
              label = "Mean RT decreases with increasing drift")

  # Effect of boundary: higher boundary should increase mean RT
  params_low_boundary <- list(drift = 3, sigma = 1, sigmabias = 0.5, boundary = 0.5, ndt = 0.3)
  params_high_boundary <- list(drift = 3, sigma = 1, sigmabias = 0.5, boundary = 1, ndt = 0.3)

  rts_low_boundary <- rcogmod_lba1(n, drift = params_low_boundary$drift, sigma = params_low_boundary$sigma,
                        sigmabias = params_low_boundary$sigmabias, boundary = params_low_boundary$boundary,
                        ndt = params_low_boundary$ndt)
  rts_high_boundary <- rcogmod_lba1(n, drift = params_high_boundary$drift, sigma = params_high_boundary$sigma,
                         sigmabias = params_high_boundary$sigmabias, boundary = params_high_boundary$boundary,
                         ndt = params_high_boundary$ndt)

  mean_low_boundary <- mean(rts_low_boundary)
  mean_high_boundary <- mean(rts_high_boundary)

  expect_true(mean_high_boundary > mean_low_boundary,
              label = "Mean RT increases with increasing boundary")
})



test_that("dcogmod_lba1 integrates correctly and returns valid densities", {
  skip_on_cran()
  set.seed(456)
  n_samples_for_range <- 5000
  tol_integration <- 1e-3  # Tolerance for integration

  # Parameter combinations
  param_combinations <- expand.grid(
    drift = c(1, 3),
    sigma = c(0.5, 1),
    sigmabias = c(0.2, 0.5),
    boundary = 0.5,
    ndt = 0.3
  )

  # 1. Integration test
  for (i in 1:nrow(param_combinations)) {
    params <- param_combinations[i, ]
    label <- sprintf("params(drift=%.1f, sigma=%.1f, sigmabias=%.1f, boundary=%.1f, ndt=%.1f)",
                     params$drift, params$sigma, params$sigmabias, params$boundary, params$ndt)

    # Define the integrand
    integrand <- function(x) {
      dcogmod_lba1(x, drift = params$drift, sigma = params$sigma,
              sigmabias = params$sigmabias, boundary = params$boundary, ndt = params$ndt)
    }

    # Determine integration upper limit using simulated RTs
    x_sample_range <- rcogmod_lba1(n_samples_for_range, drift = params$drift,
                              sigma = params$sigma, sigmabias = params$sigmabias,
                              boundary = params$boundary, ndt = params$ndt)
    if (any(is.na(x_sample_range)) || length(x_sample_range) < 2) {
      warning("Skipping integration test for ", label, " due to invalid sample range.")
      next
    }
    upper_limit <- quantile(x_sample_range, 0.9999, na.rm = TRUE) +
      10 * sd(x_sample_range, na.rm = TRUE)
    if (!is.finite(upper_limit) || upper_limit < params$ndt + 10) {
      upper_limit <- params$ndt + 100
    }

    # Compute the integral
    integral_result <- tryCatch(
      stats::integrate(integrand, lower = params$ndt + .Machine$double.eps,
                       upper = upper_limit, subdivisions = 1000,
                       rel.tol = tol_integration / 10, abs.tol = tol_integration / 10)$value,
      error = function(e) {
        warning("Integration failed for ", label, ": ", e$message)
        NA
      }
    )

    if (!is.na(integral_result)) {
      expect_equal(integral_result, 1, tolerance = tol_integration,
                   label = paste(label, "- Density integrates to 1"))
    }
  }

  # 2. Density value tests with a single parameter set
  params <- list(drift = 3, sigma = 1, sigmabias = 0.5, boundary = 0.5, ndt = 0.3)
  rt_below_ndt <- params$ndt - 0.1
  rt_at_ndt <- params$ndt
  rt_above_ndt <- params$ndt + 0.5

  # Density should be 0 for RT < ndt
  expect_equal(dcogmod_lba1(rt_below_ndt, drift = params$drift, sigma = params$sigma,
                       sigmabias = params$sigmabias, boundary = params$boundary, ndt = params$ndt),
               0, label = "Density is 0 for RT < ndt")

  # Density should be non-negative at RT = ndt
  density_at_ndt <- dcogmod_lba1(rt_at_ndt, drift = params$drift, sigma = params$sigma,
                            sigmabias = params$sigmabias, boundary = params$boundary, ndt = params$ndt)
  expect_true(density_at_ndt >= 0,
              label = "Density is non-negative at RT = ndt")

  # Density should be non-negative for RT > ndt
  density_above_ndt <- dcogmod_lba1(rt_above_ndt, drift = params$drift, sigma = params$sigma,
                               sigmabias = params$sigmabias, boundary = params$boundary, ndt = params$ndt)
  expect_true(density_above_ndt >= 0,
              label = "Density is non-negative for RT > ndt")
})



